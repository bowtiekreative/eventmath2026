    const rawDim = typeof stmt.dimension === 'number' ? stmt.dimension : 2;
    const absD   = Math.abs(rawDim);
    const dim    = rawDim < 0 ? -(absD < 2 ? 2 : absD) : (absD < 2 ? 2 : absD);
    const dimLabel = dim < 0 ? 'D-' + Math.abs(dim) : 'D+' + dim;
